    # D.EIGHT only designs: no finished-product photos anywhere (owner's rule); screen recordings instead
    ok(not pg.query_selector("#finished") and not pg.query_selector('img[src*="/p-"]'), "no finished-product section or photos on the homepage")
    ok(not hmedia, "homepage: no recording is downloaded before it is on screen")
